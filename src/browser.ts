/**
 * Browser entry of vuecli (`import ... from 'vuecli'` resolves here in browser
 * bundles built by `vuecli dev` / `vuecli build`).
 *
 * Re-exports the core API (no Node built-ins) plus the browser targets, and
 * `bootBrowser()`, which mounts an App-Router app (or any root component)
 * into the devtools console with the Turbolog target.
 */
import type { Component } from 'vue'
import { createApp, type TuiApp } from './app/app.js'
import { installDevtoolsHook } from './devtools/hook.js'
import type { ModuleLoader, RouteManifest } from './router/types.js'
import { readBoot } from './server/html.js'
import { createRouteRoot } from './server/router.js'
import { browserTarget, type BrowserTarget, type BrowserTargetOptions } from './targets/browser.js'
import { setupPageChrome } from './targets/page.js'
import { liveReload } from './targets/reload.js'

export * from './index.js'
export * from './targets/index.js'
export { setupPageChrome } from './targets/page.js'
export { liveReload } from './targets/reload.js'
export { serverRouteStub } from './server/stub.js'

export interface BootBrowserOptions extends BrowserTargetOptions {
  /** App Router manifest + module loader (generated by the build). */
  manifest?: RouteManifest
  load?: ModuleLoader
  /** Or: a plain root component. */
  root?: Component
  /** Theme name (`dark`, `light`, `dracula`) or object. */
  theme?: string
  /** Install `window.vuecli` REPL + devtools hook. Default: true. */
  devtools?: boolean
}

/**
 * Mounts the app in the browser: console target (+ optional DOM view toggled
 * from the page bar), hidden-textarea input, devtools hook, dev live reload.
 */
export async function bootBrowser(options: BootBrowserOptions = {}): Promise<TuiApp> {
  const { manifest, load, root, theme, devtools = true, ...targetOptions } = options
  const boot = readBoot()
  const path = location.pathname + location.search + location.hash
  let component = root
  if (!component) {
    if (!manifest || !load) throw new Error('[vuecli] bootBrowser needs `root` or `manifest` + `load`')
    component = await createRouteRoot({ manifest, load, path, history: 'web' })
  }
  let target: BrowserTarget | null = null
  const chrome = setupPageChrome((on) => target?.setDomView(on, chrome.root))
  target = browserTarget({ ...targetOptions, dom: targetOptions.dom ?? (chrome.dom ? chrome.root : false) })
  const app = createApp(component).mount({ target, exitOnCtrlC: false, theme })
  const rt = app.runtime!
  rt.events.on('exit', ({ error }) => {
    chrome.status(error ? `app crashed: ${String((error as Error)?.message ?? error)}` : 'app exited — reload to restart')
    if (error) console.error(error)
  })
  if (devtools) installDevtoolsHook(rt, { repl: true })
  if (boot?.reload) liveReload(boot.reload)
  return app
}
